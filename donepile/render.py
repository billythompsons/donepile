"""Formatting helpers for DonePile.

TRANSPARENCY NOTE: everything in this file is plain, deterministic Python.
It does NOT extract or invent tasks — the local model in engine.py does that.
These helpers only: (1) drop exact duplicate tasks, (2) sort High -> Medium
-> Low, (3) render Markdown / plain text, (4) estimate time saved using the
transparent formula documented in the README.
"""
from __future__ import annotations

PRIORITY_ORDER = {"High": 0, "Medium": 1, "Low": 2}

# Transparent effort-saved estimate (see README "Effort saved"):
# ~90 seconds to manually re-read, rewrite, assign and prioritise one item,
# plus ~5 minutes of initial sorting of the whole pile.
SECONDS_PER_ITEM_MANUAL = 90
PILE_SORT_MINUTES = 5


def dedupe_and_sort(tasks: list[dict]) -> list[dict]:
    seen: set[str] = set()
    unique: list[dict] = []
    for task in tasks:
        key = task["task"].strip().lower()
        if key in seen:
            continue
        seen.add(key)
        unique.append(task)
    return sorted(unique, key=lambda t: (PRIORITY_ORDER.get(t["priority"], 1), t["task"].lower()))


def estimate_minutes_saved(task_count: int) -> float:
    return round(task_count * SECONDS_PER_ITEM_MANUAL / 60 + PILE_SORT_MINUTES, 1)


def render_markdown(tasks: list[dict], source_name: str = "your notes") -> str:
    tasks = dedupe_and_sort(tasks)
    saved = estimate_minutes_saved(len(tasks))
    lines = [
        "# ✅ Your Done List",
        "",
        f"_From {source_name} — extracted locally by Qwen2.5-1.5B-Instruct (no cloud, no API key)._",
        f"_{len(tasks)} tasks · estimated manual effort saved: ~{saved} minutes_",
        "",
    ]
    for priority in ("High", "Medium", "Low"):
        group = [t for t in tasks if t["priority"] == priority]
        if not group:
            continue
        emoji = {"High": "🔴", "Medium": "🟡", "Low": "🟢"}[priority]
        lines.append(f"## {emoji} {priority} priority")
        lines.append("")
        for t in group:
            lines.append(f"- [ ] **{t['task']}** — Owner: {t['owner']} · Due: {t['due']}")
        lines.append("")
    lines.append("---")
    lines.append("Generated by DonePile · open-weight model, local CPU inference via llama.cpp")
    lines.append("")
    return "\n".join(lines)


def render_text(tasks: list[dict]) -> str:
    tasks = dedupe_and_sort(tasks)
    out = [f"DONEPILE — {len(tasks)} tasks extracted locally", "=" * 46]
    for t in tasks:
        out.append(f"[ ] ({t['priority']:<6}) {t['task']}  —  {t['owner']} · {t['due']}")
    out.append("=" * 46)
    out.append(f"Estimated manual effort saved: ~{estimate_minutes_saved(len(tasks))} minutes")
    return "\n".join(out)
