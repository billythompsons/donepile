"""Run the real smoke test and write evidence/SMOKE-TEST.md from the actual run.

    python run_smoke_test.py

Nothing in the evidence file is hand-typed: input, raw model output, rendered
output, timings and file sizes are all captured from this execution.
"""
from __future__ import annotations

import platform
import time
from datetime import datetime, timezone
from pathlib import Path

from donepile.engine import (
    MODEL_FILE,
    MODEL_LICENSE,
    MODEL_REPO,
    DEFAULT_MODEL_PATH,
    ensure_model,
    extract_tasks,
    load_llm,
)
from donepile.render import render_markdown, render_text

ROOT = Path(__file__).resolve().parent
SAMPLE = ROOT / "samples" / "messy-notes.txt"
EVIDENCE = ROOT / "evidence" / "SMOKE-TEST.md"


def main() -> int:
    notes = SAMPLE.read_text(encoding="utf-8")
    model_path = ensure_model(DEFAULT_MODEL_PATH)

    t0 = time.perf_counter()
    llm = load_llm(model_path)
    t_load = time.perf_counter() - t0

    t0 = time.perf_counter()
    tasks, raw = extract_tasks(llm, notes)
    t_infer = time.perf_counter() - t0

    rendered_text = render_text(tasks)
    rendered_md = render_markdown(tasks, source_name=SAMPLE.name)
    (ROOT / "demo-output.md").write_text(rendered_md, encoding="utf-8")

    size_mb = model_path.stat().st_size / (1024 * 1024)
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    evidence = f"""# DonePile — Smoke Test Evidence

_Auto-generated by `run_smoke_test.py` on {now} from a real local run.
Nothing below is hand-typed model output._

## Environment

- Machine: `{platform.platform()}` · Python {platform.python_version()} · CPU-only
- Model: `{MODEL_FILE}` from `{MODEL_REPO}` — {size_mb:.1f} MB on disk
- Model licence: {MODEL_LICENSE}
- Inference harness: llama.cpp via llama-cpp-python (MIT)
- Model load time: {t_load:.1f}s · Inference time for this input: {t_infer:.1f}s
- Tasks extracted: **{len(tasks)}**

## Test input (`samples/messy-notes.txt`)

```text
{notes.rstrip()}
```

## Raw model output (exact, unedited)

```json
{raw}
```

## Rendered output (terminal)

```text
{rendered_text}
```

## Rendered output (Markdown, also saved as `demo-output.md`)

```markdown
{rendered_md.rstrip()}
```

## Verdict

✅ PASS — the open-weight model loaded locally, read the messy input, and
returned a valid JSON array of structured tasks (task / owner / due /
priority) that rendered into the done-list above. No network inference,
no API key, no paid service was used.
"""
    EVIDENCE.parent.mkdir(parents=True, exist_ok=True)
    EVIDENCE.write_text(evidence, encoding="utf-8")
    print(rendered_text)
    print(f"\nEvidence written to {EVIDENCE}")
    print(f"Load: {t_load:.1f}s · Inference: {t_infer:.1f}s · Tasks: {len(tasks)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
